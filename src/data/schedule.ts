import { enforce } from '../core/enforce';
import { rng } from '../core/day';
import { PROMPTS_PER_DAY } from '../core/layers';

/**
 * The daily schedule: which categories each puzzle asks, in order. It lives in bank/schedule.md as one table
 * row per day, so it can be read and hand-edited.
 *
 * Rows for today and earlier are frozen once they exist. Regenerating (`npm run bank:schedule`) only rewrites
 * future rows and appends new ones, so approving or retiring categories never changes a day someone may already
 * be playing, or invalidates their save.
 */

export type Schedule = ReadonlyMap<number, readonly string[]>;

/** Keep at least this many days scheduled ahead; the tests fail below it, so running out shows up in CI. */
export const MIN_DAYS_AHEAD = 14;
/** How far ahead a regeneration schedules. */
export const SCHEDULE_DAYS_AHEAD = 60;
/** At most this many prompts from one domain on one day. */
export const MAX_PER_DOMAIN = 3;

export function parseSchedule(text: string): Schedule {
  const rows = new Map<number, string[]>();
  for (const [n, line] of text.split('\n').entries()) {
    if (!line.startsWith('| ') || line.startsWith('| # ') || line.startsWith('|---')) continue;
    const cells = line.slice(2, -2).split(' | ');
    enforce(cells.length === 3, `bank/schedule.md:${n + 1}: expected 3 cells (#, date, prompts), got ${cells.length}`);
    const puzzle = Number(cells[0]);
    enforce(Number.isInteger(puzzle) && puzzle >= 1, `bank/schedule.md:${n + 1}: bad puzzle number ${cells[0]}`);
    enforce(!rows.has(puzzle), `bank/schedule.md:${n + 1}: puzzle ${puzzle} appears twice`);
    const ids = cells[2]!.split(', ').map((s) => s.trim());
    enforce(ids.length === PROMPTS_PER_DAY, `bank/schedule.md:${n + 1}: puzzle ${puzzle} has ${ids.length} prompts, need ${PROMPTS_PER_DAY}`);
    enforce(new Set(ids).size === ids.length, `bank/schedule.md:${n + 1}: puzzle ${puzzle} repeats a prompt`);
    rows.set(puzzle, ids);
  }
  const nums = [...rows.keys()].sort((a, b) => a - b);
  nums.forEach((p, i) => enforce(p === i + 1, `bank/schedule.md: puzzles must run 1, 2, 3… without gaps; found ${p} at position ${i + 1}`));
  return rows;
}

export function formatSchedule(s: Schedule, dateOf: (puzzle: number) => string): string {
  const nums = [...s.keys()].sort((a, b) => a - b);
  return [
    '# Daily schedule',
    '',
    '<!-- Generated by `npm run bank:schedule`. Rows for today and earlier are frozen: regeneration only rewrites future days. -->',
    '',
    '| # | date | prompts |',
    '|---|---|---|',
    ...nums.map((p) => `| ${p} | ${dateOf(p)} | ${s.get(p)!.join(', ')} |`),
    '',
  ].join('\n');
}

/**
 * Keep rows up to and including `frozenThrough`, and generate the rest up to `through`.
 * Picks favour the categories asked longest ago, never repeat one within the cooldown (as long as the pool
 * allows it), and cap any domain at MAX_PER_DOMAIN per day. The result is deterministic.
 */
export function extendSchedule(
  current: Schedule,
  pool: readonly { id: string; domain: string }[],
  frozenThrough: number,
  through: number,
): Map<number, readonly string[]> {
  enforce(pool.length >= PROMPTS_PER_DAY, `schedule: need at least ${PROMPTS_PER_DAY} approved categories, have ${pool.length}`);
  const out = new Map<number, readonly string[]>();
  const lastAsked = new Map<string, number>();
  const domainOf = new Map(pool.map((c) => [c.id, c.domain]));
  for (let p = 1; p <= Math.min(frozenThrough, through); p++) {
    const row = current.get(p);
    if (!row) break; // the frozen prefix is only what exists
    out.set(p, row);
    for (const id of row) lastAsked.set(id, p);
  }
  const cooldown = Math.max(0, Math.floor(pool.length / PROMPTS_PER_DAY) - 1);
  for (let p = out.size + 1; p <= through; p++) {
    const r = rng(p * 7919 + 17);
    // Oldest-asked first; never-asked first of all; ties broken by a seeded shuffle.
    const order = pool
      .map((c) => ({ id: c.id, last: lastAsked.get(c.id) ?? -Infinity, tie: r() }))
      .sort((a, b) => a.last - b.last || a.tie - b.tie);
    const day: string[] = [];
    const perDomain = new Map<string, number>();
    const take = (strict: boolean) => {
      for (const c of order) {
        if (day.length === PROMPTS_PER_DAY) return;
        if (day.includes(c.id)) continue;
        if (strict && p - c.last <= cooldown) continue;
        const d = domainOf.get(c.id)!;
        if (strict && (perDomain.get(d) ?? 0) >= MAX_PER_DOMAIN) continue;
        day.push(c.id);
        perDomain.set(d, (perDomain.get(d) ?? 0) + 1);
      }
    };
    take(true);
    take(false); // a small pool can't honour the cooldown and domain cap every day; fill the rest anyway
    enforce(day.length === PROMPTS_PER_DAY, `schedule: could not fill puzzle ${p}`);
    out.set(p, day);
    for (const id of day) lastAsked.set(id, p);
  }
  return out;
}
